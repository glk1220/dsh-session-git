const DICTS = { zh, en }

/** 选择语言。samples 是用来判断的会话文本（标题、提问）。 */
export function pickLocale(setting, samples = []) {
  if (setting === 'zh' || setting === 'en') return setting
  if (samples.some((sample) => hasCjk(sample))) return 'zh'
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale
    if (typeof locale === 'string' && locale.toLowerCase().startsWith('zh')) return 'zh'
  } catch {
    // Intl 不可用时按英文处理
  }
  return 'en'
}

/** 返回 t(key, params)；键可以是 'turnEnded.error' 这种点路径。 */
export function createT(locale) {
  const dict = DICTS[locale] ?? en
  return (key, params = {}) => {
    let value = dict
    for (const part of key.split('.')) value = value?.[part]
    if (typeof value !== 'string') return key
    return value.replace(/\{(\w+)\}/gu, (match, name) => (Object.hasOwn(params, name) ? String(params[name]) : match))
  }
}
